export const PARSE_PLAN_SYSTEM = 'Ты — парсер контент-планов для Telegram-канала. Отвечай только JSON-объектом {"items":[{"day":"YYYY-MM-DD или null","topic":"...","brief":"..."}]}.';
export function parsePlanUser({ text, today, tz }) {
  return `Сегодня: ${today} (часовой пояс ${tz}).
Разбери контент-план ниже на отдельные посты, по одному элементу на пост, в том порядке, в каком они идут.
- "day": дата публикации в формате YYYY-MM-DD, если она указана или однозначно следует из текста (например «30.10», «понедельник 3 ноября»). Если года нет, бери ближайшую будущую дату. Если для поста даты нет (например «День 3», «Пост 5» или просто список) — null.
- "topic": короткая тема поста в одну строку.
- "brief": все детали и тезисы из плана, относящиеся именно к этому посту (формат, кнопки, ссылки, акценты). Ничего не выдумывай и не добавляй.
Не включай заголовки, пояснения и пустые пункты.

ПЛАН:
${text}`;
}
